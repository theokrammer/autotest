#[test]
fn test_full_lifecycle_with_staging_and_approve() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();

    // 1. Init
    handle_init(dir, false).unwrap();

    // 2. Generate from TS source
    let src_dir = dir.join("src");
    fs::create_dir_all(&src_dir).unwrap();
    fs::write(
        src_dir.join("Calculator.ts"),
        r#"
export class Calculator {
    public add(a: number, b: number): number {
        return a + b;
    }
}
"#,
    )
    .unwrap();

    handle_generate(dir, false, false, false, true).unwrap();

    let scenario_path = dir.join("tests/scenarios/Calculator.autotest.json");
    assert!(scenario_path.exists());

    // 3. Verify passes cleanly initially
    handle_verify(dir).expect("Initial verify should pass");

    // 4. Simulate recorded outcome staged to .staging.json
    let staging_path = StagingManager::staging_path_for(&scenario_path);
    let staged_entry = StagingEntry {
        target: "Calculator.add".to_string(),
        scenario: "recorded_add_live".to_string(),
        recorded_at: "2026-11-18T12:00:00Z".to_string(),
        mode: "recorded".to_string(),
        expected: serde_json::json!({ "value": 42 }),
    };
    StagingManager::write_staging(&staging_path, &[staged_entry]).unwrap();
    assert!(staging_path.exists());

    // 5. Verify should now fail because unverified staging exists
    let verify_res = handle_verify(dir);
    assert!(
        verify_res.is_err(),
        "Verify must fail when staging files are pending"
    );

    // 6. Approve staged recordings
    handle_approve(dir, None).expect("Approve should succeed");

    // 7. Staging file should be cleaned up
    assert!(!staging_path.exists(), "Staging file should be removed after approve");

    // 8. Scenario file should now include the recorded scenario
    let updated_content = fs::read_to_string(&scenario_path).unwrap();
    let updated_doc: ScenarioDocument = serde_json::from_str(&updated_content).unwrap();
    let recorded_sc = updated_doc.targets[0]
        .scenarios
        .iter()
        .find(|s| s.name == "recorded_add_live");
    assert!(
        recorded_sc.is_some(),
        "Recorded scenario must be merged into primary scenario file"
    );
    assert_eq!(recorded_sc.unwrap().mode, autotest_core::ScenarioMode::Recorded);

    // 9. Verify should now pass cleanly
    handle_verify(dir).expect("Verify must pass cleanly after approval");
}

#[test]
fn test_approve_specific_file_filter() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();

    handle_init(dir, false).unwrap();

    let src_dir = dir.join("src");
    fs::create_dir_all(&src_dir).unwrap();
    fs::write(
        src_dir.join("ServiceA.ts"),
        "export class ServiceA { public run(): void {} }",
    )
    .unwrap();
    fs::write(
        src_dir.join("ServiceB.ts"),
        "export class ServiceB { public run(): void {} }",
    )
    .unwrap();

    handle_generate(dir, false, false, false, true).unwrap();

    let path_a = dir.join("tests/scenarios/ServiceA.autotest.json");
    let path_b = dir.join("tests/scenarios/ServiceB.autotest.json");
    let staging_a = StagingManager::staging_path_for(&path_a);
    let staging_b = StagingManager::staging_path_for(&path_b);

    StagingManager::write_staging(
        &staging_a,
        &[StagingEntry {
            target: "ServiceA.run".to_string(),
            scenario: "test_a".to_string(),
            recorded_at: "2026-11-18T12:00:00Z".to_string(),
            mode: "recorded".to_string(),
            expected: serde_json::json!({ "value": null }),
        }],
    )
    .unwrap();

    StagingManager::write_staging(
        &staging_b,
        &[StagingEntry {
            target: "ServiceB.run".to_string(),
            scenario: "test_b".to_string(),
            recorded_at: "2026-11-18T12:00:00Z".to_string(),
            mode: "recorded".to_string(),
            expected: serde_json::json!({ "value": null }),
        }],
    )
    .unwrap();

    // Approve only ServiceA
    let rel_path_a = "tests/scenarios/ServiceA.autotest.json";
    handle_approve(dir, Some(rel_path_a)).expect("Approve specific file should succeed");

    assert!(!staging_a.exists(), "ServiceA staging file should be removed");
    assert!(staging_b.exists(), "ServiceB staging file should remain");

    // Now approve remaining
    handle_approve(dir, None).unwrap();
    assert!(!staging_b.exists(), "ServiceB staging file should now be removed");
}

