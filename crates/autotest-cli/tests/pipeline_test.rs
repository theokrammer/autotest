#[test]
fn test_generate_from_typescript_source() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();

    // 1. Initialize
    handle_init(dir, false).unwrap();

    // 2. Create TS source file in src/order/OrderService.ts
    let src_dir = dir.join("src").join("order");
    fs::create_dir_all(&src_dir).unwrap();

    let ts_source = r#"
export class OrderService {
    constructor(private readonly taxRate: number = 0.19) {}

    public calculateTotal(quantity: number, unitPrice: number): number {
        if (quantity <= 0) {
            throw new Error("Quantity must be positive");
        }
        return quantity * unitPrice * (1 + this.taxRate);
    }
}
"#;
    fs::write(src_dir.join("OrderService.ts"), ts_source).unwrap();

    // 3. Generate scenarios
    handle_generate(dir, false, false, false, true).expect("handle_generate should succeed");

    // 4. Assert scenario file was created in tests/scenarios/order/OrderService.autotest.json
    let scenario_file = dir.join("tests/scenarios/order/OrderService.autotest.json");
    assert!(scenario_file.exists(), "Scenario file should be created");

    let content = fs::read_to_string(&scenario_file).unwrap();
    let doc: ScenarioDocument = serde_json::from_str(&content).expect("Valid ScenarioDocument");

    assert_eq!(doc.schema_version, "1.0");
    assert_eq!(doc.targets.len(), 1);
    assert_eq!(doc.targets[0].id, "OrderService.calculateTotal");
    assert!(!doc.targets[0].scenarios.is_empty(), "Scenarios should be generated by solver");

    // 5. Verify suite passes cleanly
    handle_verify(dir).expect("handle_verify should pass cleanly on newly generated scenarios");
}

